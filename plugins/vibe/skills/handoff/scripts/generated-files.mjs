// Build output, marked `linguist-generated` in the base's `.gitattributes` or by a generator header: one predicate
// every handoff diff rule reads, so a generated copy is judged through its hand-written source.

import { execFileSync } from "node:child_process";

/**
 * Head paths whose `linguist-generated` attribute is set by the `.gitattributes` at `base`, so a diff cannot mark its
 * own hand-written files generated and skip the rules that read them. A git that cannot read attributes at a commit
 * (`--source` needs git 2.40) marks nothing generated, so every rule still reads every file.
 */
export function linguistGenerated(worktree, files, base) {
  if (files.length === 0) return new Set();
  let output;
  try {
    output = execFileSync("git", ["-C", worktree, "check-attr", "-z", "--stdin", "--source", base, "linguist-generated"],
      { input: files.join("\0"), encoding: "utf8", maxBuffer: 64 * 1024 * 1024, stdio: ["pipe", "pipe", "pipe"] });
  } catch {
    return new Set();
  }
  const fields = output.split("\0");
  const generated = new Set();
  for (let index = 0; index + 2 < fields.length; index += 3) {
    if (fields[index + 2] === "set" || fields[index + 2] === "true") generated.add(fields[index]);
  }
  return generated;
}

/**
 * Whether `file` is build output a diff rule judges through its source: the base's `.gitattributes` marks it
 * `linguist-generated` (`repo.generatedFiles`, from linguistGenerated), or, with `header` (the default), its path is
 * minified or one of its first five lines is a generator comment the base already had when the base has the file, so
 * a diff cannot exempt its own source by adding one. duplicate-helper passes `header: false`: it still flags a
 * generated bundle that copies a helper it did not inline.
 */
export function isGeneratedFile(repo, file, { header = true } = {}) {
  if (repo.generatedFiles?.has(file) === true) return true;
  if (!header) return false;
  if (MINIFIED.test(file)) return true;
  if (!hasGeneratorHeader(repo.head(file))) return false;
  const base = repo.base?.(file);
  return base == null || hasGeneratorHeader(base);
}

/** Whether one of the first five lines of `text` is a generator comment: "Generated by … do not edit", or `@generated`. */
export function hasGeneratorHeader(text) {
  if (typeof text !== "string") return false;
  let start = 0;
  for (let line = 0; line < HEADER_LINES && start <= text.length; line += 1) {
    const end = text.indexOf("\n", start);
    if (GENERATOR_HEADER.test(text.slice(start, end < 0 ? text.length : end))) return true;
    if (end < 0) return false;
    start = end + 1;
  }
  return false;
}

const HEADER_LINES = 5;
const GENERATOR_HEADER = /^\s*(?:\/\/|#|\/?\*+|<!--).*(?:\bgenerated by\b.*\bdo not edit\b|@generated\b)/i;
const MINIFIED = /\.min\.(?:js|mjs|css)$/;
