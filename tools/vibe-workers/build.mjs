import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { buildBundles } from "../shared/build-bundles.mjs";

const toolDir = dirname(fileURLToPath(import.meta.url));
const outdir = resolve(toolDir, "../../plugins/vibe/skills/vibe/scripts/dist");
const vibeCoreDir = resolve(toolDir, "../../plugins/vibe-core");
const vibeCoreLoader = resolve(toolDir, "../../plugins/vibe/shared/vibe-core.mjs");

// A module that lives in vibe-core is loaded from the installed vibe-core at run time, never
// inlined, so no copy of it ships in vibe (ISS-13869). The stub re-exports the module's names.
const loadVibeCoreAtRunTime = {
  name: "vibe-core-at-run-time",
  setup(builder) {
    builder.onResolve({ filter: /\.mjs$/ }, (args) => {
      const target = resolve(args.resolveDir, args.path);
      return target.startsWith(`${vibeCoreDir}/`)
        ? { path: target.slice(vibeCoreDir.length + 1), namespace: "vibe-core", pluginData: target }
        : undefined;
    });
    builder.onLoad({ filter: /.*/, namespace: "vibe-core" }, async (args) => {
      const names = Object.keys(await import(args.pluginData)).filter((name) => name !== "default").sort();
      return {
        resolveDir: dirname(vibeCoreLoader),
        contents: `import { vibeCore } from ${JSON.stringify(vibeCoreLoader)};\n`
          + `const module = await vibeCore(${JSON.stringify(args.path)});\n`
          + `export const { ${names.join(", ")} } = module;\n`,
      };
    });
  },
};
const banner = "// Generated by tools/vibe-workers/build.mjs; do not edit.\nimport { createRequire as __vibeRequire } from 'node:module'; import {fileURLToPath as __vibeFileURL} from 'node:url'; import {dirname as __vibeDir} from 'node:path'; const require = __vibeRequire(import.meta.url); const __filename = __vibeFileURL(import.meta.url); const __dirname = __vibeDir(__filename);";
await buildBundles({
  build,
  toolDir,
  outdir,
  isEntry: (file) => ["writer-state.ts", "claude-worker.ts", "main-sync.ts", "scope-intake.ts"].includes(file),
  // The bundled compiler parser initializes its filesystem adapter using CommonJS path globals.
  banner,
  extra: { plugins: [loadVibeCoreAtRunTime] },
});
await build({
  entryPoints: [resolve(toolDir, "src/qa-impact-parser.ts")],
  outfile: resolve(outdir, "qa-impact-parser.mjs"),
  bundle: true,
  minify: true,
  platform: "node",
  format: "esm",
  target: "node18",
  banner: { js: banner },
  plugins: [loadVibeCoreAtRunTime],
});
console.log(`built the bundled QA-impact parser to ${outdir}`);
// Preserve the bundled Apache notice while removing its upstream whitespace-only comment lines.
for (const name of readdirSync(outdir).filter((file) => file.endsWith(".mjs"))) {
  const path = resolve(outdir, name);
  const source = readFileSync(path, "utf8");
  // Package-manager layout must not change generated module labels or bundle diffs.
  const normalized = source.replace(/node_modules\/\.pnpm\/[^/]+\/node_modules\//g, "node_modules/");
  const notice = normalized.lastIndexOf("/*! Bundled license information:");
  const output = notice >= 0
    ? normalized.slice(0, notice) + normalized.slice(notice).split("\n").map((line) => line.trimEnd()).join("\n")
    : normalized;
  if (output !== source) writeFileSync(path, output);
}
